"""Preserve source clip durations and STEP scales lost by the Tiny3D importer."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

from glb_assets import read_glb

CLIPS = ("Idle", "Run", "Jump", "Dash", "Climb.Idle", "Climb.Up", "Skid")
ENUM_NAMES = {"Climb.Idle": "ClimbIdle", "Climb.Up": "ClimbUp"}


def accessor_values(document: dict, binary: bytes, index: int) -> list[tuple[float, ...]]:
    accessor = document["accessors"][index]
    if accessor["componentType"] != 5126 or "sparse" in accessor:
        raise ValueError("Animation source requires nonsparse FLOAT accessors")
    width = {"SCALAR": 1, "VEC3": 3, "VEC4": 4}[accessor["type"]]
    view = document["bufferViews"][accessor["bufferView"]]
    stride = view.get("byteStride", width * 4)
    start = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
    count = accessor["count"]
    if stride < width * 4 or start + (count - 1) * stride + width * 4 > len(binary):
        raise ValueError("Animation accessor outside GLB binary")
    result = [struct.unpack_from("<" + "f" * width, binary, start + i * stride) for i in range(count)]
    if not all(math.isfinite(value) for row in result for value in row):
        raise ValueError("Nonfinite animation source")
    return result


def source_metadata(path: Path) -> tuple[list[float], list[dict]]:
    document, binary = read_glb(path)
    animations = {animation["name"]: animation for animation in document["animations"]}
    joint_names = [document["nodes"][index]["name"] for index in document["skins"][0]["joints"]]
    if len(joint_names) != len(set(joint_names)):
        raise ValueError("Ambiguous source bone names")
    durations = []
    tracks = []
    for clip in CLIPS:
        animation = animations[clip]
        duration = max(accessor_values(document, binary, sampler["input"])[-1][0]
                       for sampler in animation["samplers"])
        if duration <= 0:
            raise ValueError(f"Invalid duration for {clip}")
        durations.append(duration)
        for channel in animation["channels"]:
            sampler = animation["samplers"][channel["sampler"]]
            if sampler.get("interpolation", "LINEAR") != "STEP":
                continue
            values = accessor_values(document, binary, sampler["output"])
            if all(value == values[0] for value in values):
                continue
            if channel["target"]["path"] != "scale":
                raise ValueError("Varying STEP channel requires additional runtime support")
            name = document["nodes"][channel["target"]["node"]]["name"]
            if name not in joint_names:
                raise ValueError(f"STEP target is not a skin joint: {name}")
            times = [row[0] for row in accessor_values(document, binary, sampler["input"])]
            if len(times) != len(values) or not 1 <= len(times) <= 32:
                raise ValueError("STEP channel outside fixed key budget")
            if times[0] < 0 or any(a >= b for a, b in zip(times, times[1:])):
                raise ValueError("Unordered STEP key times")
            tracks.append({"clip": clip, "bone": name, "times": times, "values": values})
    if len(tracks) > 32:
        raise ValueError("STEP tracks outside fixed runtime budget")
    return durations, tracks


def float_literal(value: float) -> str:
    result = format(value, ".9g")
    if "." not in result and "e" not in result:
        result += ".0"
    return result + "f"


def render_header(source: Path) -> str:
    durations, tracks = source_metadata(source)
    keys = []
    rows = []
    for track in tracks:
        rows.append(f'    {{PlayerAnimState::{ENUM_NAMES.get(track["clip"], track["clip"])}, '
                    f'{json.dumps(track["bone"])}, {len(keys)}, {len(track["times"])}}},')
        for time, value in zip(track["times"], track["values"]):
            keys.append("    {" + float_literal(time) + ", {" + ", ".join(map(float_literal, value)) + "}},")
    sha = hashlib.sha256(source.read_bytes()).hexdigest()
    return "\n".join([
        "// Generated by tools/generate_player_animation_source.py; do not edit.",
        "#pragma once", '#include "gameplay/player/animation_state.hpp"',
        "namespace madeline_cube {", f'constexpr const char* kPlayerAnimationSourceSha256 = "{sha}";',
        "struct PlayerSourceScaleKey { float time; float scale[3]; };",
        "struct PlayerSourceScaleTrack { PlayerAnimState clip; const char* bone; int offset; int count; };",
        "constexpr float kPlayerSourceClipDurations[] = {" + ", ".join(map(float_literal, durations)) + "};",
        "constexpr PlayerSourceScaleKey kPlayerSourceScaleKeys[] = {", *keys, "};",
        "constexpr PlayerSourceScaleTrack kPlayerSourceScaleTracks[] = {", *rows, "};",
        f"constexpr int kPlayerSourceScaleTrackCount = {len(tracks)};",
        "inline const PlayerSourceScaleKey& SamplePlayerSourceScale(int track_index, float time) {",
        "    const auto& track = kPlayerSourceScaleTracks[track_index];",
        "    int key = track.offset;",
        "    while (key + 1 < track.offset + track.count && kPlayerSourceScaleKeys[key + 1].time <= time) ++key;",
        "    return kPlayerSourceScaleKeys[key];", "}", "} // namespace madeline_cube", "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = render_header(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
