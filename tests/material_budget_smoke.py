#!/usr/bin/env python3
"""Check that the baked room only references TMEM-safe 3D materials."""

from pathlib import Path
import struct


MANIFEST = Path("filesystem/lvl/first-room.manifest")
TEXTURES = Path("assets/og_converted/textures")
BYTES_PER_RGBA16_PIXEL = 2
TMEM_BYTES = 4096


def read_sprite_size(path: Path) -> tuple[int, int]:
    data = path.read_bytes()
    assert data[:4] != b"DCA5", f"{path} must be uncompressed for direct budget inspection"
    width, height = struct.unpack(">HH", data[:4])
    return width, height


def read_sprite_lod_sizes(path: Path) -> list[tuple[int, int]]:
    data = path.read_bytes()
    width, height = struct.unpack_from(">HH", data)
    sizes = [(width, height)]
    if not (data[5] & 0x80):
        return sizes
    base_bytes = (width * height * BYTES_PER_RGBA16_PIXEL + 7) & ~7
    ext = 8 + base_bytes
    assert struct.unpack_from(">H", data, ext + 2)[0] == 6, f"{path}: unknown sprite extension version"
    for lod in range(7):
        lod_width, lod_height = struct.unpack_from(">HH", data, ext + 8 + lod * 8)
        if not lod_width or not lod_height:
            break
        sizes.append((lod_width, lod_height))
    return sizes


def main() -> None:
    materials = [line.strip() for line in MANIFEST.read_text().splitlines() if line.strip()]
    assert materials, "level manifest is empty"

    for material in materials:
        sprite_path = TEXTURES / f"{material}.sprite"
        assert sprite_path.exists(), f"missing sprite for material {material}"
        width, height = read_sprite_size(sprite_path)
        byte_count = width * height * BYTES_PER_RGBA16_PIXEL
        assert byte_count <= TMEM_BYTES, (
            f"{material} is {width}x{height} RGBA16 ({byte_count} bytes), "
            f"which exceeds {TMEM_BYTES}-byte TMEM"
        )
        print(f"PASS: {material} {width}x{height} RGBA16 uses {byte_count} bytes")

    # Whole-map profile sidecar (generated by bake-forsaken-city).  Keep the
    # legacy first-room check above because older levels intentionally have no
    # sidecar.
    matmeta = Path("filesystem/lvl/forsyken-city/forsyken-city.matmeta")
    map_manifest = Path("filesystem/lvl/forsyken-city/forsyken-city.manifest")
    if matmeta.exists() and map_manifest.exists():
        map_materials = [line.rstrip("\r\n") for line in map_manifest.read_text().splitlines()]
        rows = matmeta.read_text(encoding="utf-8").splitlines()
        header = rows.pop(0).split("\t")
        assert header[:2] == ["MATMETA", "1"] and int(header[2]) == len(map_materials)
        assert len(rows) == len(map_materials)
        for expected_id, (name, row) in enumerate(zip(map_materials, rows)):
            fields = row.split("\t")
            assert len(fields) == 10, f"matmeta row {expected_id} has {len(fields)} fields"
            assert int(fields[0]) == expected_id and fields[1] == name
            assert fields[3] in {"none", "world_repeat_rgba16", "world_decal_rgba16"}
            if fields[3] == "none":
                assert fields[2] == "" and fields[4] == "none" and fields[7] == "none"
            else:
                assert fields[2].startswith("rom:/tex/")
                sprite = Path("filesystem") / fields[2][len("rom:/"):]
                assert sprite.exists(), f"missing map sprite {sprite}"
                width, height = read_sprite_size(sprite)
                assert width * height * BYTES_PER_RGBA16_PIXEL <= TMEM_BYTES
                lod_sizes = read_sprite_lod_sizes(sprite)
                if fields[3] == "world_repeat_rgba16":
                    expected = [(width, height)]
                    while min(expected[-1][0] // 2, expected[-1][1] // 2) >= 4:
                        prev_width, prev_height = expected[-1]
                        expected.append((prev_width // 2, prev_height // 2))
                    assert lod_sizes == expected, f"{sprite}: mip chain {lod_sizes} != {expected}"
                    mip_bytes = sum(w * h * BYTES_PER_RGBA16_PIXEL for w, h in lod_sizes)
                    assert mip_bytes <= TMEM_BYTES, f"{sprite}: mip chain uses {mip_bytes} TMEM bytes"
                    assert fields[7] == "bilinear", f"{sprite}: expected bilinear filter metadata"
                elif fields[3] == "world_decal_rgba16":
                    assert lod_sizes == [(width, height)], f"{sprite}: alpha decal unexpectedly mipmapped"
                    assert fields[7] == "bilinear", f"{sprite}: expected bilinear filter metadata"
        print(f"PASS: Forsaken City matmeta {len(map_materials)} materials")

    print("material budget smoke test: PASS")


if __name__ == "__main__":
    main()
